/* -------------------------------- */
/* ACTIVE EFFECT */
/* -------------------------------- */

let activeEffect =
	null;

/* -------------------------------- */
/* GET */
/* -------------------------------- */

export function getActiveEffect() {

	return activeEffect;
}

/* -------------------------------- */
/* SET */
/* -------------------------------- */

export function setActiveEffect(
	effect
) {

	activeEffect =
		effect;
}